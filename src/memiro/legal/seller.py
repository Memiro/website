"""Реквизиты продавца — обязательны к публикации (п. 18 ПП РФ 2463).

Правила дистанционной продажи требуют показать покупателю полное
наименование юрлица либо ФИО ИП, ОГРН(ИП), адрес места нахождения
и способ связи. Витрина печатает их одинаково в футере
и на «Контактах», политика обработки ПД — как оператора.

Значения вписывает владелец прямо сюда — правка реквизита должна быть
минутным коммитом, а не походом в админку. Пустое поле не печатается:
неверный ОГРН хуже отсутствующего. О незаполненных полях предупреждает
`manage.py check` (см. `checks.py`) — иначе сайт молча оказался бы
без названного продавца.
"""

from __future__ import annotations

from dataclasses import dataclass, field, fields
from typing import Any


def _line(label: str) -> Any:  # noqa: ANN401
    """Поле реквизита с подписью, под которой оно печатается."""
    return field(default="", metadata={"label": label})


@dataclass(frozen=True)
class Seller:
    """Продавец, каким его видит покупатель.

    Порядок полей задаёт порядок строк на витрине; подпись едет
    в метаданных поля, чтобы новое поле нельзя было завести
    без подписи.
    """

    # «ИП Фамилия Имя Отчество» либо полное наименование юрлица.
    # Печатается без подписи — читается как имя продавца
    name: str = _line("")
    # ОГРНИП (15 цифр) для ИП либо ОГРН (13 цифр) для юрлица
    ogrn: str = _line("ОГРН/ОГРНИП")
    # Не требуется правилами, но по нему покупатель находит продавца
    # в ЕГРИП/ЕГРЮЛ — самая дешёвая проверка добросовестности
    inn: str = _line("ИНН")
    # Адрес места нахождения — не адрес шоурума (тот в SiteContacts)
    address: str = _line("Адрес")

    def requisites(self) -> list[tuple[str, str]]:
        """Заполненные реквизиты парами «подпись — значение»."""
        return [
            (item.metadata["label"], getattr(self, item.name))
            for item in fields(self)
            if getattr(self, item.name)
        ]

    def missing(self) -> list[str]:
        """Имена незаполненных полей — для проверки перед выкладкой."""
        return [
            item.name for item in fields(self) if not getattr(self, item.name)
        ]


# ВНИМАНИЕ: владелец обязан заполнить все поля ДО запуска сайта.
SELLER = Seller()

"""Список id через запятую — как его принимают эндпоинты витрины.

Форма у него одна на весь API: подборка товаров присылает так корзину
и избранное, расчёт — выбранные значения атрибутов. Правило разбора
живёт в одном месте, чтобы вторая копия однажды не разошлась с первой.
"""

from __future__ import annotations

# Список id через запятую либо пусто: пустой список — не ошибка
IDS_PATTERN = r"^(\d+(,\d+)*)?$"

# Длины хватает на сотню девятизначных id с запятыми
MAX_IDS_LENGTH = 1000


def parse_ids(raw: str) -> list[int]:
    """Разбирает список в порядке запроса; пустые куски отбрасывает."""
    return [int(chunk) for chunk in raw.split(",") if chunk]

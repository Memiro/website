def resolve(category: Category) -> dict[str, AttributeValue]:
    """Значения справочника под условия всех шести посадочных.

    Перенос заводит только те значения, что встретились у товаров, —
    любого из шести в базе может не оказаться. Сверяем весь список до
    первой записи, иначе прогон падает на середине и откатывает уже
    созданное.
    """
    values: dict[str, AttributeValue] = {}
    missing: list[str] = []
    for plan in PLANS:
        value = AttributeValue.objects.filter(
            attribute__category=category,
            attribute__slug=plan.attribute,
            value=plan.value,
        ).first()
        if value is None:
            missing.append(f"{plan.attribute} = {plan.value}")
        else:
            values[plan.slug] = value
    if missing:
        listing = "\n  ".join(missing)
        message = f"Нет значений в справочнике:\n  {listing}"
        raise SystemExit(message)
    return values


TEXT_FIELDS = ("title", "heading", "description", "text")


def texts_of(plan: Plan) -> dict[str, str]:
    """Четыре текстовых поля посадочной — одним словарём.

    Один список полей и на заведение, и на перезапись: разъедься они,
    новое поле попало бы только в одну из двух веток.
    """
    return {field: getattr(plan, field) for field in TEXT_FIELDS}


def retext(landing: Landing, plan: Plan) -> bool:
    """Переписать тексты посадочной. True, если что-то менялось.

    Обложку, публикацию, порядок и условия не трогаем: их владелец
    ставит руками, и к текстам они отношения не имеют.
    """
    changed = [
        field
        for field, value in texts_of(plan).items()
        if getattr(landing, field) != value
    ]
    if not changed:
        return False
    for field in changed:
        setattr(landing, field, getattr(plan, field))
    landing.save(update_fields=changed)
    return True


def main(*, rewrite_texts: bool = False) -> None:
    category = Category.objects.filter(slug=CATEGORY_SLUG).first()
    if category is None:
        raise SystemExit(f"Нет категории «{CATEGORY_SLUG}»")
    # Справочник нужен только под новые посадочные: их условия ссылаются
    # на его значения. Перезапись текстов от него не зависит, и падать
    # на его неполноте ей не за что
    values: dict[str, AttributeValue] | None = None
    with transaction.atomic():
        for order, plan in enumerate(PLANS):
            existing = Landing.objects.filter(slug=plan.slug).first()
            if existing is not None:
                if not rewrite_texts:
                    print(f"= {plan.slug}: уже заведена, пропуск")
                elif retext(existing, plan):
                    print(f"~ {plan.slug}: тексты перезаписаны")
                else:
                    print(f"= {plan.slug}: тексты уже совпадают")
                continue
            if values is None:
                values = resolve(category)
            value = values[plan.slug]
            landing = Landing.objects.create(
                category=category,
                slug=plan.slug,
                is_published=True,
                order=order,
                **texts_of(plan),
            )
            LandingCondition.objects.create(
                landing=landing,
                attribute=value.attribute,
                value_option=value,
            )
            print(f"+ {plan.slug}: {plan.heading}")


